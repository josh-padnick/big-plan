// Embeds the authored plan-writing guidance and every component's usage
// guidance as generated TypeScript constants, so `big-plan guidance` ships
// one versioned copy of the authoring principles without runtime file reads.

import { createHash } from "node:crypto";
import { globSync, readFileSync, writeFileSync } from "node:fs";
import { basename, join } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = fileURLToPath(new URL("..", import.meta.url));
const guidancePath = join(repoRoot, "assets", "guidance", "plan-guidance.md");
const outputPath = join(
  repoRoot,
  "src",
  "cli",
  "guidance",
  "content.generated.ts",
);

const guidance = readFileSync(guidancePath, "utf8");

// Component usage guidance is authored inside each component's slice as
// <component-kebab>.guidance.md; the component name derives from the file name.
const componentName = (fileName) =>
  basename(fileName, ".guidance.md")
    .split("-")
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join("");

const componentGuidance = Object.fromEntries(
  globSync(join(repoRoot, "src", "components", "*", "*.guidance.md"))
    .sort()
    .map((path) => [componentName(path), readFileSync(path, "utf8")]),
);

// The version identifies the guidance content itself: acknowledgments recorded
// against one version expire when any authored guidance changes.
const version = createHash("sha256")
  .update(guidance)
  .update(JSON.stringify(componentGuidance))
  .digest("hex")
  .slice(0, 12);

writeFileSync(
  outputPath,
  [
    "// Generated by scripts/gen-guidance.mjs from assets/guidance/ and",
    "// src/components/*/*.guidance.md. Do not edit.",
    "",
    `export const GUIDANCE_MARKDOWN = ${JSON.stringify(guidance)};`,
    "",
    `export const COMPONENT_GUIDANCE: Readonly<Record<string, string>> = ${JSON.stringify(componentGuidance, null, 2)};`,
    "",
    `export const GUIDANCE_VERSION = ${JSON.stringify(version)};`,
    "",
  ].join("\n"),
  "utf8",
);
console.log(
  `generated ${outputPath} (guidance version ${version}, ${Object.keys(componentGuidance).length} components)`,
);
