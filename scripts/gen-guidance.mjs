// Embeds the authored plan-writing guidance and every component's usage
// guidance as generated TypeScript constants, so `big-plan guidance` ships
// one versioned copy of the authoring principles without runtime file reads.

import { createHash } from "node:crypto";
import { globSync, readFileSync, writeFileSync } from "node:fs";
import { basename, join } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const repoRoot = fileURLToPath(new URL("..", import.meta.url));
const guidancePath = join(repoRoot, "assets", "guidance", "plan-guidance.md");
const outputPath = join(
  repoRoot,
  "src",
  "cli",
  "guidance",
  "content.generated.ts",
);

const guidance = readFileSync(guidancePath, "utf8");
const slideCatalogPath = join(
  repoRoot,
  "src",
  "plan-vocabulary",
  "slide-types",
  "index.ts",
);

// The catalog is authored as framework-free TypeScript so every product layer
// consumes the same checked records. Bundle it in memory for this build-time
// continuation instead of maintaining a second prose copy for guidance.
const [{ text: slideCatalogModule }] = (
  await build({
    entryPoints: [slideCatalogPath],
    bundle: true,
    format: "esm",
    platform: "node",
    target: "node22",
    write: false,
  })
).outputFiles;
const slideCatalog = await import(
  `data:text/javascript;base64,${Buffer.from(slideCatalogModule).toString("base64")}`
);
if (!Array.isArray(slideCatalog.SLIDE_TYPES)) {
  throw new Error("Slide type catalog did not export SLIDE_TYPES");
}

const renderSlideTypeCatalog = (types) =>
  [
    "## The catalog",
    "",
    ...types.flatMap((type) => [
      `### ${type.name} (\`${type.id}\`)`,
      "",
      `**Use it when:** ${type.match.when}`,
      "",
      `**Do not use it when:** ${type.match.notWhen}`,
      "",
      `**Structure:** ${type.cardinality === "many" ? "May repeat." : "At most one per plan."}${type.placement === "last-typed" ? " It is the last typed slide." : ""}`,
      "",
      "**Write it well:**",
      "",
      ...type.guidance.map((line) => `- ${line}`),
      "",
      "**Components that pair well:**",
      "",
      ...type.components.map(
        (component) => `- \`${component.name}\` — ${component.guidance}`,
      ),
      "",
    ]),
  ].join("\n");

// Component usage guidance is authored inside each component's slice as
// <component-kebab>.guidance.md; the component name derives from the file name.
const componentName = (fileName) =>
  basename(fileName, ".guidance.md")
    .split("-")
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join("");

const componentGuidance = Object.fromEntries(
  globSync(join(repoRoot, "src", "components", "*", "*.guidance.md"))
    .sort()
    .map((path) => {
      const name = componentName(path);
      const authored = readFileSync(path, "utf8");
      return [
        name,
        name === "Slide"
          ? authored.replace(
              "{{SLIDE_TYPE_CATALOG}}",
              renderSlideTypeCatalog(slideCatalog.SLIDE_TYPES),
            )
          : authored,
      ];
    }),
);

// The version identifies the guidance content itself: acknowledgments recorded
// against one version expire when any authored guidance changes.
const version = createHash("sha256")
  .update(guidance)
  .update(JSON.stringify(componentGuidance))
  .digest("hex")
  .slice(0, 12);

writeFileSync(
  outputPath,
  [
    "// Generated by scripts/gen-guidance.mjs from assets/guidance/ and",
    "// src/components/*/*.guidance.md, including the slide-type catalog.",
    "",
    `export const GUIDANCE_MARKDOWN = ${JSON.stringify(guidance)};`,
    "",
    `export const COMPONENT_GUIDANCE: Readonly<Record<string, string>> = ${JSON.stringify(componentGuidance, null, 2)};`,
    "",
    `export const GUIDANCE_VERSION = ${JSON.stringify(version)};`,
    "",
  ].join("\n"),
  "utf8",
);
console.log(
  `generated ${outputPath} (guidance version ${version}, ${Object.keys(componentGuidance).length} components)`,
);
