// Embeds the authored plan-writing guidance as a generated TypeScript
// constant, so `big-plan guidance` ships one versioned copy of the authoring
// principles without runtime file reads.

import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = fileURLToPath(new URL("..", import.meta.url));
const guidancePath = join(repoRoot, "assets", "guidance", "plan-guidance.md");
const outputPath = join(
  repoRoot,
  "src",
  "cli",
  "guidance",
  "content.generated.ts",
);

const guidance = readFileSync(guidancePath, "utf8");

// The version identifies the guidance content itself: acknowledgments recorded
// against one version expire when the authored guidance changes.
const version = createHash("sha256")
  .update(guidance)
  .digest("hex")
  .slice(0, 12);

writeFileSync(
  outputPath,
  [
    "// Generated by scripts/gen-guidance.mjs from assets/guidance/. Do not edit.",
    "",
    `export const GUIDANCE_MARKDOWN = ${JSON.stringify(guidance)};`,
    "",
    `export const GUIDANCE_VERSION = ${JSON.stringify(version)};`,
    "",
  ].join("\n"),
  "utf8",
);
console.log(`generated ${outputPath} (guidance version ${version})`);
