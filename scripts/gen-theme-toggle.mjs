// Compiles the authored theme-toggle browser script into a generated module
// the shell can inline after type-checking all browser-side TypeScript.

import { spawnSync } from "node:child_process";
import { readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const sourcePath = join(repoRoot, "src", "render", "shell", "theme-toggle.browser.ts");
const outputPath = join(repoRoot, "src", "render", "shell", "theme-toggle.generated.ts");

const check = spawnSync(
  process.execPath,
  [join(repoRoot, "node_modules", "typescript", "bin", "tsc"), "-p", "tsconfig.browser.json"],
  { cwd: repoRoot, stdio: "inherit" },
);
if (check.status !== 0) {
  process.exit(check.status ?? 1);
}

const source = await readFile(sourcePath, "utf8");
const { outputText } = ts.transpileModule(source, {
  compilerOptions: {
    target: ts.ScriptTarget.ES2023,
    module: ts.ModuleKind.None,
    removeComments: true,
  },
});

const banner =
  "// Generated by scripts/gen-theme-toggle.mjs from src/render/shell/theme-toggle.browser.ts. Do not edit.";
const moduleText = `${banner}\nexport const THEME_TOGGLE_JS = ${JSON.stringify(outputText)};\n`;
await writeFile(outputPath, moduleText, "utf8");
console.log(`generated ${outputPath} (${outputText.length} bytes of JS)`);
