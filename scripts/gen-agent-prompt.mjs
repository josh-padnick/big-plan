// Embeds the authored coding-agent prompt addition so the packaged CLI ships
// it without relying on repository files at runtime.

import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = fileURLToPath(new URL("..", import.meta.url));
const sourcePath = join(repoRoot, "src", "review", "agent-prompt.md");
const outputPath = join(repoRoot, "src", "review", "agent-prompt.generated.ts");
const prompt = readFileSync(sourcePath, "utf8").replace(
  /^<!--[\s\S]*?-->\s*/u,
  "",
);

writeFileSync(
  outputPath,
  `// Generated by scripts/gen-agent-prompt.mjs from src/review/agent-prompt.md.\n\nexport const OPERATOR_AGENT_PROMPT = ${JSON.stringify(prompt.trim())};\n`,
);
