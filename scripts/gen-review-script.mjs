// Bundles assets/review/review.js with esbuild and wraps the result in a
// generated TypeScript module, so the shell can embed the reviewer's script
// while the authored source stays an ordinary, lintable, formattable file
// instead of a string inside a template literal.

import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync } from "node:fs";
import { writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = fileURLToPath(new URL("..", import.meta.url));
const inputPath = join(repoRoot, "assets", "review", "review.js");
const outputPath = join(
  repoRoot,
  "src",
  "render",
  "shell",
  "review-script.generated.ts",
);
const esbuildBin = join(repoRoot, "node_modules", ".bin", "esbuild");

const tempDir = mkdtempSync(join(tmpdir(), "big-plan-review-"));
try {
  const bundlePath = join(tempDir, "review.js");
  execFileSync(
    esbuildBin,
    [
      inputPath,
      "--bundle",
      "--format=iife",
      "--target=es2022",
      "--minify",
      `--outfile=${bundlePath}`,
    ],
    { cwd: repoRoot, stdio: ["ignore", "inherit", "inherit"] },
  );
  const bundle = readFileSync(bundlePath, "utf8").trim();

  // A document embeds this inline, so the one sequence that could end the
  // script element early is neutralized before it can appear in the page.
  const inert = bundle.replaceAll("</script", "<\\/script");

  // Escape for a template literal so the bundle survives the round trip.
  const escaped = inert
    .replaceAll("\\", "\\\\")
    .replaceAll("`", "\\`")
    .replaceAll("${", "\\${");

  writeFileSync(
    outputPath,
    `// Generated by scripts/gen-review-script.mjs from assets/review/review.js.\n// Do not edit.\n\nexport const REVIEW_SCRIPT_BODY = \`${escaped}\`;\n`,
    "utf8",
  );
  console.log(`generated ${outputPath} (${bundle.length} bytes of script)`);
} finally {
  rmSync(tempDir, { recursive: true, force: true });
}
