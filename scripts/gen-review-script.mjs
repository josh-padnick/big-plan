// Type-checks and bundles the React review interaction island into the
// generated module the shell embeds in every self-contained HTML document.

import { spawnSync } from "node:child_process";
import { writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const sourcePath = join(
  repoRoot,
  "src",
  "review",
  "browser",
  "review.browser.tsx",
);
const outputPath = join(
  repoRoot,
  "src",
  "render",
  "review-script.generated.ts",
);

const check = spawnSync(
  process.execPath,
  [
    join(repoRoot, "node_modules", "typescript", "bin", "tsc"),
    "-p",
    "tsconfig.browser.json",
  ],
  { cwd: repoRoot, stdio: "inherit" },
);
if (check.status !== 0) {
  process.exit(check.status ?? 1);
}

const result = await build({
  entryPoints: [sourcePath],
  bundle: true,
  platform: "browser",
  format: "iife",
  target: "es2023",
  legalComments: "none",
  minify: true,
  write: false,
});
const bundle = result.outputFiles[0]?.text;
if (bundle === undefined) {
  throw new Error(`Browser bundler produced no output for ${sourcePath}`);
}

// A document embeds this inline, so neutralize the only sequence that could
// close the script element before serializing it into a TypeScript string.
const inert = bundle.replace(/<\/script/gi, "<\\/script");
const moduleText = `// Generated by scripts/gen-review-script.mjs from src/review/browser/review.browser.tsx. Do not edit.\n\nexport const REVIEW_SCRIPT_BODY = ${JSON.stringify(inert)};\n`;
await writeFile(outputPath, moduleText, "utf8");
console.log(`generated ${outputPath} (${bundle.length} bytes of script)`);
