// Compiles every authored browser script into a generated TypeScript module
// the shell can inline, after one shared browser-side type-check.

import { spawnSync } from "node:child_process";
import { readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const shellRoot = join(repoRoot, "src", "render", "shell");
const browserScripts = [
  { name: "scroll-spy", exportName: "SCROLL_SPY_JS" },
  { name: "theme-toggle", exportName: "THEME_TOGGLE_JS" },
  { name: "copy-code", exportName: "COPY_CODE_JS" },
];

const check = spawnSync(
  process.execPath,
  [join(repoRoot, "node_modules", "typescript", "bin", "tsc"), "-p", "tsconfig.browser.json"],
  { cwd: repoRoot, stdio: "inherit" },
);
if (check.status !== 0) {
  process.exit(check.status ?? 1);
}

for (const { name, exportName } of browserScripts) {
  const sourcePath = join(shellRoot, `${name}.browser.ts`);
  const outputPath = join(shellRoot, `${name}.generated.ts`);
  const source = await readFile(sourcePath, "utf8");
  const { outputText } = ts.transpileModule(source, {
    compilerOptions: {
      target: ts.ScriptTarget.ES2023,
      module: ts.ModuleKind.None,
      removeComments: true,
    },
  });
  const banner =
    `// Generated by scripts/gen-browser-scripts.mjs from src/render/shell/${name}.browser.ts. Do not edit.`;
  const moduleText =
    `${banner}\nexport const ${exportName} = ${JSON.stringify(outputText)};\n`;
  await writeFile(outputPath, moduleText, "utf8");
  console.log(`generated ${outputPath} (${outputText.length} bytes of JS)`);
}
