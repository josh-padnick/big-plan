// Compiles every authored browser script into a generated TypeScript module
// the shell can inline, after one shared browser-side type-check.
//
// This deliberately fills the narrow browser-build role that a bundler such
// as Vite normally owns: Big Plan is currently a Node CLI whose output is one
// self-contained HTML file, while tsc alone cannot hand the renderer browser
// JavaScript as inlineable strings. Once a server owns a browser application,
// its Vite build can become the canonical source for served assets; the static
// render envelope will still need to consume and inline that build output to
// preserve `big-plan render`'s single-file, offline-friendly contract.

import { spawnSync } from "node:child_process";
import { writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const renderRoot = join(repoRoot, "src", "render");
const browserScripts = [
  { directory: "shell", name: "scroll-spy", exportName: "SCROLL_SPY_JS" },
  { directory: "shell", name: "theme-toggle", exportName: "THEME_TOGGLE_JS" },
  {
    directory: "markdown/code-block",
    name: "copy-code",
    exportName: "COPY_CODE_JS",
  },
  {
    directory: "markdown/components/code-diff",
    name: "code-diff",
    exportName: "CODE_DIFF_JS",
  },
  {
    directory: "markdown/components/code-snippet",
    name: "code-snippet",
    exportName: "CODE_SNIPPET_JS",
  },
  {
    directory: "markdown/components/file-tree",
    name: "file-tree",
    exportName: "FILE_TREE_JS",
  },
  {
    directory: "markdown/components/http-endpoint",
    name: "http-endpoint",
    exportName: "HTTP_ENDPOINT_JS",
  },
];

const check = spawnSync(
  process.execPath,
  [
    join(repoRoot, "node_modules", "typescript", "bin", "tsc"),
    "-p",
    "tsconfig.browser.json",
  ],
  { cwd: repoRoot, stdio: "inherit" },
);
if (check.status !== 0) {
  process.exit(check.status ?? 1);
}

for (const { directory, name, exportName } of browserScripts) {
  const sourcePath = join(renderRoot, directory, `${name}.browser.ts`);
  const outputPath = join(renderRoot, directory, `${name}.generated.ts`);
  const result = await build({
    entryPoints: [sourcePath],
    bundle: true,
    platform: "browser",
    format: "iife",
    target: "es2023",
    legalComments: "none",
    write: false,
  });
  const outputText = result.outputFiles[0]?.text;
  if (outputText === undefined) {
    throw new Error(`Browser bundler produced no output for ${sourcePath}`);
  }
  const banner = `// Generated by scripts/gen-browser-scripts.mjs from src/render/${directory}/${name}.browser.ts. Do not edit.`;
  const moduleText = `${banner}\nexport const ${exportName} = ${JSON.stringify(outputText)};\n`;
  await writeFile(outputPath, moduleText, "utf8");
  console.log(`generated ${outputPath} (${outputText.length} bytes of JS)`);
}
