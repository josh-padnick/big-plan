// Compiles the authored browser script (src/render/shell/scroll-spy.browser.ts) into a
// generated TypeScript module the shell can inline. Two steps: type-check
// against tsconfig.browser.json (the main tsconfig has no DOM lib), then
// strip types with the TypeScript transpiler and wrap the JS as a constant.

import { spawnSync } from "node:child_process";
import { readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const sourcePath = join(repoRoot, "src", "render", "shell", "scroll-spy.browser.ts");
const outputPath = join(repoRoot, "src", "render", "shell", "scroll-spy.generated.ts");

const check = spawnSync(
  process.execPath,
  [join(repoRoot, "node_modules", "typescript", "bin", "tsc"), "-p", "tsconfig.browser.json"],
  { cwd: repoRoot, stdio: "inherit" },
);
if (check.status !== 0) {
  process.exit(check.status ?? 1);
}

const source = await readFile(sourcePath, "utf8");
// removeComments keeps authoring comments out of shipped documents; it also
// guards against a comment ever containing "</script>", which would terminate
// the inline script tag early.
const { outputText } = ts.transpileModule(source, {
  compilerOptions: {
    target: ts.ScriptTarget.ES2023,
    module: ts.ModuleKind.None,
    removeComments: true,
  },
});

const banner =
  "// Generated by scripts/gen-scroll-spy.mjs from src/render/shell/scroll-spy.browser.ts. Do not edit.";
const moduleText = `${banner}\nexport const SCROLL_SPY_JS = ${JSON.stringify(outputText)};\n`;
await writeFile(outputPath, moduleText, "utf8");
console.log(`generated ${outputPath} (${outputText.length} bytes of JS)`);
